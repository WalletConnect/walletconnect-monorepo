#!/usr/bin/env bash
# Builds the Sign v3 Rust SDK (yttrium crates/sign-v3) to WASM and embeds it in src/v3/wasm:
#   sign_v3.js, sign_v3.d.ts   the wasm-bindgen glue, --target web
#   wasm-data.ts               the module, brotli-compressed and base64-encoded, as Pay embeds yttrium
#
#   scripts/sync-v3-wasm.sh              stable release build
#   NIGHTLY=1 scripts/sync-v3-wasm.sh    the smaller nightly build
# YTTRIUM_DIR defaults to a yttrium checkout next to walletconnect-monorepo. WASM_BINDGEN picks the
# wasm-bindgen CLI, which must match the crate's wasm-bindgen version.
set -euo pipefail

here=$(cd "$(dirname "$0")/.." && pwd)
root=$(cd "$here/../.." && pwd)
yt=$(cd "${YTTRIUM_DIR:-$root/../yttrium}" && pwd)
out=$here/src/v3/wasm
bindgen=${WASM_BINDGEN:-wasm-bindgen}
want=0.2.114

if ! "$bindgen" --version | grep -q "$want"; then
  echo "wasm-bindgen $want is required, found: $("$bindgen" --version)" >&2
  echo "install it with: cargo install wasm-bindgen-cli --version $want, or set WASM_BINDGEN" >&2
  exit 1
fi

args=(-p sign-v3 --release --target wasm32-unknown-unknown --no-default-features --features wasm
  --manifest-path "$yt/Cargo.toml")
if [ "${NIGHTLY:-}" = 1 ]; then
  RUSTFLAGS="-Zunstable-options -Cpanic=immediate-abort -Zlocation-detail=none -Zfmt-debug=none" \
    cargo +nightly build "${args[@]}" -Z build-std=std,panic_abort -Z build-std-features=optimize_for_size
else
  cargo build "${args[@]}"
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
"$bindgen" --target web --out-dir "$tmp" "$yt/target/wasm32-unknown-unknown/release/sign_v3.wasm"
if command -v wasm-opt >/dev/null; then
  wasm-opt -Oz --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext \
    --enable-mutable-globals "$tmp/sign_v3_bg.wasm" -o "$tmp/sign_v3_bg.wasm"
fi

# The bytes are always passed in. Bundlers treat `new URL(file, import.meta.url)` as an asset to
# bundle, and there is no .wasm file in the package to find.
fallback="module_or_path = new URL('sign_v3_bg.wasm', import.meta.url);"
grep -qF "$fallback" "$tmp/sign_v3.js" || { echo "wasm-bindgen glue changed: $fallback not found" >&2; exit 1; }
node -e '
  const fs = require("fs");
  const [file, fallback] = process.argv.slice(1);
  fs.writeFileSync(file, fs.readFileSync(file, "utf8").replace(fallback, "throw new Error(\"sign_v3: pass the WASM bytes to init\");"));
' "$tmp/sign_v3.js" "$fallback"

mkdir -p "$out"
cp "$tmp/sign_v3.js" "$tmp/sign_v3.d.ts" "$out/"
source_rev="yttrium $(git -C "$yt" rev-parse --short HEAD)$(git -C "$yt" diff --quiet -- crates/sign-v3 && git -C "$yt" ls-files --error-unmatch crates/sign-v3/Cargo.toml >/dev/null 2>&1 || echo "+local")"
node -e '
  const fs = require("fs");
  const zlib = require("zlib");
  const [wasm, dest, source] = process.argv.slice(1);
  const bytes = fs.readFileSync(wasm);
  const compressed = zlib.brotliCompressSync(bytes, { params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11 } });
  fs.writeFileSync(dest, [
    "// Auto-generated by scripts/sync-v3-wasm.sh: the Sign v3 WASM, brotli-compressed, base64.",
    `export const SIGN_V3_WASM_SOURCE = ${JSON.stringify(source)};`,
    `export const SIGN_V3_WASM = "${compressed.toString("base64")}";`,
    "",
  ].join("\n"));
  console.log(`wasm ${bytes.length} bytes, brotli ${compressed.length}, base64 ${Math.ceil(compressed.length / 3) * 4}`);
' "$tmp/sign_v3_bg.wasm" "$out/wasm-data.ts" "$source_rev"

npx --prefix "$root" prettier --write "$out/sign_v3.js" "$out/sign_v3.d.ts" "$out/wasm-data.ts" >/dev/null
echo "embedded $source_rev in $out"
